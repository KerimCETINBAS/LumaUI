;(function()
    local draft=new(editor.require('draft.Draft').EditorDraft)
    draft:Load({version=1,kind='preset',id='native-editor',name='Native editor',sources={},root={id='root',type='fragment',props={}}})
    draft:Add('blizzardElement')
    assert(draft.Selected.kind=='blizzardElement',tostring(draft.message))
    local id=draft.Selected.id
    assert(not draft:IsVisual(draft.Selected) and #draft:Children(id)==1,'registration is headless with a visual child template')
    assert(draft.sources[1].type=='unitToBool' and draft.Selected.props.filter==draft.sources[1].name)
    local doc=draft:Document();assert(doc.root.children[1].type=='blizzardElement')
    local sample=LumaUI.Presets:Preview(doc);assert(sample.View and sample.View.kind=='cell');sample:Dispose()
    draft.propertyEditor:Ensure()
    local inspector=ui:Mount(editor.require('inspector.PropertyInspector').PropertyInspector(nil,{draft=draft,width=420,height=700}))
    ui:Unmount(inspector)
    draft:SetBlizzardMode(false)
    assert(draft.Selected.props.apply==true and #draft:Children(id)==0 and not draft:CanContain(draft.Selected),tostring(draft.message))
    local applied=LumaUI.Presets:Preview(draft:Document());assert(applied.View==nil);applied:Dispose()
    draft:Undo()
    assert(draft.Selected.props.replace==true and #draft:Children(id)==1,'mode changes retain template through Undo')
    draft:SetBlizzardMode(false);draft:SetBlizzardMode(true)
    assert(draft.Selected.props.replace==true and #draft:Children(id)==1)
    local before=#draft.nodes;draft.selected=draft:Children(id)[1].id;draft:Add('action')
    assert(#draft.nodes==before,'secure controls cannot be authored inside a nameplate template')
    print('Luma nameplate editor checks passed')
end)()
